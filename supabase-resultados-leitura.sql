-- Estrutura para o painel Leitura em Marília
-- Execute no SQL Editor do Supabase uma única vez.
--
-- A chave (ano, semana_num, codigo_escola) preserva o histórico semanal:
-- reimportar uma semana substitui apenas os registros daquele ano/semana.
-- Leitura pública (o painel não exige login); gravação/exclusão exigem ADM.

create table if not exists public.resultados_leitura_semanais (
  id bigint generated by default as identity primary key,
  ano integer not null check (ano between 2020 and 2100),
  semana_num integer not null check (semana_num between 1 and 53),
  periodo_inicio date not null,
  periodo_fim date not null,
  diretoria text not null default 'MARILIA',
  codigo_escola text not null,
  escola text not null,
  total_matriculas integer check (total_matriculas >= 0),
  alunos_ativos integer check (alunos_ativos >= 0),
  percentual_ativos numeric,
  percentual_acertos numeric,
  indice_questoes_corretas numeric,
  paginas_lidas integer check (paginas_lidas >= 0),
  livros_concluidos integer check (livros_concluidos >= 0),
  tempo_leitura_min numeric check (tempo_leitura_min >= 0),
  tempo_semanal_aluno_min numeric check (tempo_semanal_aluno_min >= 0),
  fonte_arquivo text,
  importado_em timestamptz not null default now(),
  constraint resultados_leitura_semanais_periodo_valido check (periodo_fim >= periodo_inicio),
  constraint resultados_leitura_semanais_unica unique (ano, semana_num, codigo_escola)
);

create index if not exists resultados_leitura_semanais_periodo_idx
  on public.resultados_leitura_semanais (diretoria, periodo_inicio, codigo_escola);

alter table public.resultados_leitura_semanais enable row level security;

-- Leitura pública: o painel leia-sp.html é acessado sem login.
drop policy if exists "Leitura semanal pública" on public.resultados_leitura_semanais;
create policy "Leitura semanal pública"
  on public.resultados_leitura_semanais
  for select
  to anon, authenticated
  using (true);

-- Gravação/exclusão apenas para administradores ativos (ADM/ADMIN), usada pelo admin.html.
drop policy if exists "Insert apenas ADM em resultados_leitura_semanais" on public.resultados_leitura_semanais;
create policy "Insert apenas ADM em resultados_leitura_semanais"
  on public.resultados_leitura_semanais
  for insert to authenticated
  with check (
    exists (
      select 1 from public.perfis_usuarios p
      where p.id = auth.uid() and p.escopo in ('ADM', 'ADMIN') and p.ativo = true
    )
  );

drop policy if exists "Delete apenas ADM em resultados_leitura_semanais" on public.resultados_leitura_semanais;
create policy "Delete apenas ADM em resultados_leitura_semanais"
  on public.resultados_leitura_semanais
  for delete to authenticated
  using (
    exists (
      select 1 from public.perfis_usuarios p
      where p.id = auth.uid() and p.escopo in ('ADM', 'ADMIN')
    )
  );

grant select on public.resultados_leitura_semanais to anon, authenticated;
grant insert, delete on public.resultados_leitura_semanais to authenticated;

notify pgrst, 'reload schema';
